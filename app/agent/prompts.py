TIME_GAP_NOTE = """【时间提醒】距离上次对话已过去 {days} 天。在继续之前，先向用户确认这期间可能变化的情况，不要直接沿用之前的计划或假设。"""


def build_system(time_gap_days: int | None = None) -> str:
    if time_gap_days and time_gap_days >= 3:
        return SYSTEM + "\n\n" + TIME_GAP_NOTE.format(days=time_gap_days)
    return SYSTEM
